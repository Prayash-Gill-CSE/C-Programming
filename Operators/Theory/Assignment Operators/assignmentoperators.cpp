// Assignment operators are used for the assigning the value to the variable.

#include <iostream>
using namespace std;

int main()
{
    int a = 10;     // 10 value is assigned to the a.
    double b = 90;  // 90 value is assigned to the b.
    float c = 10.0; // 10.0 value is assigned to the c.
    cout << a << " " << b << " " << c;
    return 0;
}

/*
We have more types of assignment operators:
1. += --> Add and assign
2. -= --> Substract and assign
3. *= --> Multiply and assign
4. /+ --> Divide and assign
5. %= --> Modulus and assign
*/