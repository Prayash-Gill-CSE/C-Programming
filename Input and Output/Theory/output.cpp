// Output is used to the print the statement through which the user can understand the computer language.

#include <iostream>
using namespace std;

int main()
{
    int a;                              // Variable declaration
    cout << "Enter the value of a: ";   // User understandable
    cin >> a;                           // input of a from the user
    cout << "The value of a is: " << a; // cout is used to print the value or give the output
    return 0;
}

/*
cout is used to print the output on the screen in the human understandable format.
In this we use "<<" this kind of symbols to print the statement.
*/