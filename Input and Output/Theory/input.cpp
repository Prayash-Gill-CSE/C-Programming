// Input is used to take the values and data from the user according to their need.

#include <iostream>
using namespace std;

int main()
{
    int A;                            // Variable declaration.
    cout << "Enter the value of A: "; // Used to show the user what they have to enter.
    cin >> A;                         // cin is used to take the input from the user.
    return 0;
}

/*
cin is used to take input.
this ">>" kind of symbol is used to take the value to that variable.
It stores the value in the buffer.

*/