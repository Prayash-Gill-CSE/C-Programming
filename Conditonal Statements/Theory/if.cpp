// The if statement runs a block of code only when a condition is true.

#include <iostream>
using namespace std;

int main()
{
    int age = 10; // age variable is initialized
    if (age <= 18)
    {                                                             // if statement is written
        cout << "Not able to vote now wait! till the 18 or 18+."; // what action we have to do if the statement becomes true
    }
    return 0;
}

/*
This statement runs only when the condition is true other wise the other conditions run.
*/