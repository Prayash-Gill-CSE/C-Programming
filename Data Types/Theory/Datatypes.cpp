// #Datatypes are used to distinguish between different types of data like the number, char, string etc.

#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    float b = 12.3;
    string c = "Hello";
    char d = 'J';
    double e = 12.2222222;
    bool f = true;
    long g = 654321;
    cout << a << "\n";
    cout << b << "\n";
    cout << c << "\n";
    cout << d << "\n";
    cout << e << "\n";
    cout << f << "\n";
    cout << g << "\n";
    return 0;
}


/*
                       SIZE OF DIFFERENT TYPES OF DATATYPES
                       int(4)                whole numbers
                       float(4)              decimal numbers
                       double(8)             large decimal numbers
                       char(1)               a single character
                       bool(1)               true/false
                       long(4/8)             large whole number
*/