// Helps to repeat the statement more than one  time.

#include <iostream>
using namespace std;

int main()
{
    int i = 0; // initialization
    while (i < 5)
    {              // loop
        cout << i; // output
        i++;       // increment
    }
    return 0;
}

/*
A while loop repeats a block of code as long as its condition stays true.
Best when you don't know exactly how many times to repeat.
*/